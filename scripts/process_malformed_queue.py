def process_queue(report_path: str, dry_run: bool = False, limit: int = 0):
    """Process all malformed posts in the report."""
    load_dotenv()
    
    # Load report
    with open(report_path) as f:
        items = json.load(f)
    
    if not items:
        print("No malformed posts to process")
        return
    
    print(f"Found {len(items)} malformed posts to process")
    
    if limit > 0:
        items = items[:limit]
        print(f"Limiting to {limit} items")
    
    # Group by handle (bot account)
    by_handle = {}
    for item in items:
        handle = item['handle']
        if handle not in by_handle:
            by_handle[handle] = []
        by_handle[handle].append(item)
    
    # Track results
    processed = 0
    deleted = 0
    failed = 0
    
    # Process each bot's posts
    for handle, posts in by_handle.items():
        print(f"\n{'='*60}")
        print(f"Processing {len(posts)} posts for {handle}")
        print(f"{'='*60}")
        
        # Get credentials
        creds = BOT_CREDENTIALS.get(handle)
        if not creds:
            print(f"  ⚠️ Unknown handle: {handle}, skipping")
            failed += len(posts)
            continue
        
        bot_handle = os.environ.get(creds['handle_env'])
        bot_password = os.environ.get(creds['password_env'])
        
        if not bot_handle or not bot_password:
            print(f"  ⚠️ Missing credentials for {handle}, skipping")
            failed += len(posts)
            continue
        
        # Authenticate
        if not dry_run:
            try:
                client = Client()
                client.login(bot_handle, bot_password)
                print(f"  ✓ Authenticated as {bot_handle}")
            except Exception as e:
                print(f"  ❌ Auth failed: {e}")
                failed += len(posts)
                continue
        
        # Process each post
        for item in posts:
            uri = item['uri']
            original_text = item['text']
            external_url = item['external_url']
            
            # Extract clean title
            clean_title = extract_clean_title(original_text)
            council_name = extract_council_name(original_text)
            
            print(f"\n  📰 Original: {original_text[:60]}...")
            print(f"  🔧 Clean title: {clean_title}")
            print(f"  🏛️ Council: {council_name}")
            print(f"  🔗 URL: {external_url[:60]}...")
            
            if dry_run:
                print(f"  [DRY RUN] Would delete: {uri}")
                print(f"  [DRY RUN] Would NOT repost (scraper should fix at source)")
                processed += 1
                continue
            
            # DELETE the old malformed post
            # We do NOT repost here - the scraper should re-scrape and post correctly
            # with the safety valve in place
            try:
                if delete_post(client, uri):
                    print(f"  ✓ Deleted malformed post")
                    deleted += 1
                    processed += 1
                else:
                    failed += 1
            except Exception as e:
                print(f"  ❌ Error: {e}")
                failed += 1
            
            # Rate limit
            time.sleep(0.5)
    
    # Summary
    print(f"\n{'='*60}")
    print("SUMMARY")
    print(f"{'='*60}")
    print(f"Processed: {processed}")
    print(f"Deleted: {deleted}")
    print(f"Failed: {failed}")
    
    if not dry_run and deleted > 0:
        # Clear the processed items from the report
        remaining = [item for item in items if item not in items[:processed]]
        with open(report_path, 'w') as f:
            json.dump(remaining, f, indent=2)
        print(f"\nUpdated report: {len(remaining)} items remaining")


