def extract_clean_title(text: str) -> str:
    """
    Extract just the title from a malformed post text.
    
    The malformed posts have format:
    "Title + Body snippet...\nDate\nCouncil\n#Hashtags"
    
    We need to extract just the title.
    """
    if not text:
        return ""
    
    # Split on first newline - title is before it
    lines = text.split('\n')
    first_line = lines[0].strip()
    
    # The title often gets merged with the body/excerpt
    # Look for patterns where the body starts
    
    # Pattern 1: Date at the end of first line "Title 03 December 2025 Body..."
    date_pattern = r'\s+\d{1,2}\s+(?:January|February|March|April|May|June|July|August|September|October|November|December)\s+\d{4}\s+'
    match = re.search(date_pattern, first_line, re.IGNORECASE)
    if match:
        # Title is before the date
        title = first_line[:match.start()].strip()
        return title
    
    # Pattern 2: "Published on XX Month YYYY" embedded
    published_pattern = r'Published on \d{1,2} \w+ \d{4}'
    match = re.search(published_pattern, first_line, re.IGNORECASE)
    if match:
        title = first_line[:match.start()].strip()
        return title
    
    # Pattern 3: Repeated sentence start (title + first sentence of body)
    # e.g., "King tides expected from Friday Townsville City Council is encouraging..."
    # Split at common sentence starters after title
    body_starters = [
        r'(?<=[a-z])\s+(?:The|A|An|Council|City|Shire|Mayor|Residents|Locals|More than|As|Pet|Getting|At|On|Over|In|Following|The City|City of)\s+[A-Z]',
    ]
    for pattern in body_starters:
        match = re.search(pattern, first_line)
        if match:
            title = first_line[:match.start() + 1].strip()  # +1 to include the lowercase letter
            return title
    
    # Pattern 4: Title ends with recognizable council phrase
    # Look for repeated content pattern
    # Many posts have "Title Body preview..." where title might end with key noun
    
    # Fallback: If first line is very long (>100 chars), try to find a logical break
    if len(first_line) > 100:
        # Look for sentence ending followed by capital letter start
        sentence_break = re.search(r'[.!?]\s+[A-Z]', first_line)
        if sentence_break:
            # Assume title is the first sentence
            potential_title = first_line[:sentence_break.start() + 1]
            if len(potential_title) < 150:
                return potential_title
        
        # Try ellipsis truncation point
        if '...' in first_line:
            # The ... is usually where content was truncated
            # Title is probably the first part before significant body text
            pass
    
    # Last resort: truncate at reasonable length
    if len(first_line) > 120:
        # Find last space before 120 chars
        truncate_at = first_line[:120].rfind(' ')
        if truncate_at > 0:
            return first_line[:truncate_at]
    
    return first_line


def extract_council_name(text: str) -> str:
    """Extract council name from post text."""
    lines = text.split('\n')
    # Council name is typically the 3rd or 4th line (after Title, Date)
    for line in lines[1:4]:
        line = line.strip()
        # Skip if it's a date or hashtags
        if line.startswith('#') or not line:
            continue
        if re.match(r'\d{1,2}\s+\w+\s+\d{4}', line):
            continue
        # Likely the council name
        if 'Council' in line or 'Shire' in line or 'City of' in line:
            return line
    return ""


def delete_post(client: Client, uri: str) -> bool:
    """Delete a post by URI."""
    try:
        # Extract rkey from URI
        # Format: at://did:plc:xxx/app.bsky.feed.post/rkey
        parts = uri.split('/')
        rkey = parts[-1]
        
        client.delete_post(rkey)
        return True
    except Exception as e:
        print(f"  ❌ Failed to delete post: {e}")
        return False


